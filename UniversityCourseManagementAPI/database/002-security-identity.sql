-- Module 5-8 database migration for an existing University Course Management database.
-- Run once against PostgreSQL when upgrading a database created by Module 1-4.

CREATE TABLE IF NOT EXISTS "AspNetRoles" (
  "Id" text NOT NULL PRIMARY KEY, "Name" varchar(256), "NormalizedName" varchar(256), "ConcurrencyStamp" text
);
CREATE UNIQUE INDEX IF NOT EXISTS "RoleNameIndex" ON "AspNetRoles" ("NormalizedName") WHERE "NormalizedName" IS NOT NULL;

CREATE TABLE IF NOT EXISTS "AspNetUsers" (
  "Id" text NOT NULL PRIMARY KEY, "UserName" varchar(256), "NormalizedUserName" varchar(256),
  "Email" varchar(256), "NormalizedEmail" varchar(256), "EmailConfirmed" boolean NOT NULL,
  "PasswordHash" text, "SecurityStamp" text, "ConcurrencyStamp" text, "PhoneNumber" text,
  "PhoneNumberConfirmed" boolean NOT NULL, "TwoFactorEnabled" boolean NOT NULL,
  "LockoutEnd" timestamptz, "LockoutEnabled" boolean NOT NULL, "AccessFailedCount" integer NOT NULL,
  "StudentId" integer, "TeacherId" integer,
  CONSTRAINT "FK_AspNetUsers_Students_StudentId" FOREIGN KEY ("StudentId") REFERENCES "Students"("Id") ON DELETE SET NULL,
  CONSTRAINT "FK_AspNetUsers_Teachers_TeacherId" FOREIGN KEY ("TeacherId") REFERENCES "Teachers"("Id") ON DELETE SET NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "UserNameIndex" ON "AspNetUsers" ("NormalizedUserName") WHERE "NormalizedUserName" IS NOT NULL;
CREATE INDEX IF NOT EXISTS "EmailIndex" ON "AspNetUsers" ("NormalizedEmail");
CREATE INDEX IF NOT EXISTS "IX_AspNetUsers_StudentId" ON "AspNetUsers" ("StudentId");
CREATE INDEX IF NOT EXISTS "IX_AspNetUsers_TeacherId" ON "AspNetUsers" ("TeacherId");

CREATE TABLE IF NOT EXISTS "AspNetRoleClaims" (
  "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "RoleId" text NOT NULL,
  "ClaimType" text, "ClaimValue" text,
  CONSTRAINT "FK_AspNetRoleClaims_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES "AspNetRoles"("Id") ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS "IX_AspNetRoleClaims_RoleId" ON "AspNetRoleClaims" ("RoleId");

CREATE TABLE IF NOT EXISTS "AspNetUserClaims" (
  "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "UserId" text NOT NULL,
  "ClaimType" text, "ClaimValue" text,
  CONSTRAINT "FK_AspNetUserClaims_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS "IX_AspNetUserClaims_UserId" ON "AspNetUserClaims" ("UserId");

CREATE TABLE IF NOT EXISTS "AspNetUserLogins" (
  "LoginProvider" varchar(128) NOT NULL, "ProviderKey" varchar(128) NOT NULL, "ProviderDisplayName" text, "UserId" text NOT NULL,
  PRIMARY KEY ("LoginProvider", "ProviderKey"),
  CONSTRAINT "FK_AspNetUserLogins_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS "IX_AspNetUserLogins_UserId" ON "AspNetUserLogins" ("UserId");

CREATE TABLE IF NOT EXISTS "AspNetUserRoles" (
  "UserId" text NOT NULL, "RoleId" text NOT NULL, PRIMARY KEY ("UserId", "RoleId"),
  CONSTRAINT "FK_AspNetUserRoles_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
  CONSTRAINT "FK_AspNetUserRoles_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES "AspNetRoles"("Id") ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS "IX_AspNetUserRoles_RoleId" ON "AspNetUserRoles" ("RoleId");

CREATE TABLE IF NOT EXISTS "AspNetUserTokens" (
  "UserId" text NOT NULL, "LoginProvider" varchar(128) NOT NULL, "Name" varchar(128) NOT NULL, "Value" text,
  PRIMARY KEY ("UserId", "LoginProvider", "Name"),
  CONSTRAINT "FK_AspNetUserTokens_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE
);
